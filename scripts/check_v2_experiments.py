#!/usr/bin/env python3
"""Integrity checks for the experiments added in v2 after review (post hoc).

1. The six archived policies, regenerated by the v2 driver, equal the archived
   ablation_raw.csv row by row (switches, sign-change rate, entropy, t_sfx, censored).
2. CW with b=0 equals immediate argmin (same switch counts in every row).
3. Row counts and keys of the new raw CSVs; tuning is reproducible from the
   committed grid (selected parameter = argmin of the tuning loss, ties to the
   earlier grid point).
4. The committed tables and V2_results.md equal the regenerated ones.
5. The tables are present verbatim in paper/arxiv/main.tex and arxiv_ref.
Standard library only; exit 0 = GREEN.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "paper/arxiv_ref/tools"))
import gen_v2_tables as g  # noqa: E402

ARCHIVE = {"full (제안)": "full", "-hysteresis": "hyst0", "-progress hardening": "hard0",
           "-accumulator (즉시 argmin)": "argmin", "simple-dwell (O4)": "dwell_0.6",
           "-class correspondence": "noclass"}


def fail(msg):
    print(f"[RED] {msg}")
    return 1


def main():
    bad = 0
    arch = list(csv.DictReader((ROOT / "src/compass_eval/results/ablation_raw.csv").open(encoding="utf-8")))
    nat = {(r["policy"], r["scenario"], r["seed"]): r for r in g.data("v2_native_raw.csv")}
    if len(nat) != 11 * 250:
        bad += fail(f"native raw rows {len(nat)} != 2750")
    cols = [("switches", "switches"), ("sign_change_rate", "sign_change_rate"),
            ("decision_entropy", "decision_entropy"), ("t_legible_s", "t_sfx_s"), ("censored", "censored")]
    for r in arch:
        n = nat[(ARCHIVE[r["variant"]], r["scenario"], r["seed"])]
        for a, b in cols:
            if float(r[a]) != float(n[b]):
                bad += fail(f"archived row differs: {r['variant']} {r['scenario']} {r['seed']} {a}")
    if not bad:
        print(f"[GREEN] {len(arch)} archived rows reproduced by the v2 driver")
    grid_cw0 = {k: v for k, v in
                {(r["scenario"], r["seed"]): r["switches"] for r in g.data("v2_native_raw.csv")
                 if r["policy"] == "argmin"}.items()}
    for r in g.data("tuning_grid.csv"):
        if r["split"] == "eval" and r["rule"] == "cw" and r["param"] == "b=0":
            ref = g.native("argmin", r["scenario"], "switches", "mean")
            if abs(float(r["mean_switches"]) - ref) > 1e-9:
                bad += fail(f"CW b=0 differs from argmin in {r['scenario']}")
    if len(g.data("v2_sigma_raw.csv")) != 10 * 5 * 5 * 50:
        bad += fail("sigma raw rows != 12500")
    if len(g.data("v2_late_reversal_raw.csv")) != 9 * 4 * 50:
        bad += fail("late raw rows != 1800")
    # tuning reproducibility from the committed grid
    for rule in ("compass_E0", "dwell", "cw", "li"):
        params = list(dict.fromkeys(r["param"] for r in g.data("tuning_grid.csv") if r["rule"] == rule))
        losses = [g.grid("tune", rule, p, "*", "mean_loss") for p in params]
        best = params[min(range(len(params)), key=lambda i: (round(losses[i], 12), i))]
        if best != g.sel_param(rule)[0]:
            bad += fail(f"selected parameter for {rule} is {g.sel_param(rule)[0]}, grid says {best}")
    if g.main([]) != 0:
        bad += 1
    main_tex = (ROOT / "paper/arxiv/main.tex").read_text(encoding="utf-8")
    for name, text in g.build().items():
        body = [ln for ln in text.splitlines() if " & " in ln and ln.endswith("\\\\")]
        for ln in body:
            if ln not in main_tex:
                bad += fail(f"{name}: row missing from paper/arxiv/main.tex: {ln[:60]}")
        ref = (ROOT / "paper/arxiv_ref/sections/4_experiments.tex").read_text(encoding="utf-8")
        if f"\\input{{tables/{name}}}" not in ref and name not in ref:
            bad += fail(f"{name}: not included in arxiv_ref sections")
    if not bad:
        print("[GREEN] v2 experiments: archived rows, tuning, tables and both manuscripts agree")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
